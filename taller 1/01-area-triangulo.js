// EJERCICIO 1 - AREA DE UN TRIANGULO
// Formula AT = (B * H) / 2
// AT = area del triangulo
// B = Base
// H = Altura
// ==================================

// Cambiar estos valores para probar el programa con otros datos

const base = 5; // Base del triangulo (numero)
const altura = 4; // Altura del triangulo (numero)

// Aplicamos la Formula del area (base por altura dividido entre dos).
const areaTriangulo = (base * altura) / 2;

// Mostrar en consola los datos de entrada junto al reultado obtenido.
console.log("===== AREA DE UN TRIANGULO =====");
console.log("La base es: ; ", base) // Imprime el valor de la base.
console.log("La altura es: ;", altura ) // Imprimer el valor de la altura.
console.log("El area del triangulo es: ;",  areaTriangulo) // Imprime el valor del area del triangulo.
